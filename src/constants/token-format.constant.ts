import { deepFreeze } from '../deep-freeze';

/**
 * Форма токена: `v2.<полезная нагрузка base64url>.<HMAC-SHA256 base64url>`.
 * Нагрузка: `p:<system_identifier>:<линия времени>:<X/Y>:<выдан, мс эпохи>` или
 * `u:<выдан, мс эпохи>` (позицию определить не смогли). Длиннее потолка — отказ
 * до разбора: токен приходит из заголовка или cookie клиента, и разбирать
 * произвольный объём незачем. Токены `v1` (без момента выдачи) — `invalid`.
 */
export const TOKEN_FORMAT = {
  VERSION: 'v2',
  /** Разделение доменов подписи: тот же секрет в другом месте не даёт годной подписи здесь. */
  DOMAIN: 'pg-replica-sync/token/v2',
  MAX_LENGTH: 256,
  MIN_SECRET_BYTES: 32,
  /** Ключ с меньшей эмпирической энтропией гистограммы байтов (бит на весь ключ) — отказ. */
  MIN_SECRET_HISTOGRAM_BITS: 64,
  /** Ключ, который deflate сжимает до меньшего числа бит, — отказ (почти-повтор). */
  MIN_SECRET_COMPRESSED_BITS: 128,
  /** HMAC-SHA256. */
  MAC_BYTES: 32,
  /** Метка нагрузки с позицией. */
  POSITION_TAG: 'p',
  /** Метка нагрузки токена, выданного без позиции. */
  UNRESOLVED_TAG: 'u',
  /** Момент выдачи: десятичное без ведущих нулей, не длиннее 16 цифр (≤ 2⁵³ проверяется отдельно). */
  ISSUED_AT_TEXT: /^(0|[1-9][0-9]{0,15})$/,
} as const;
deepFreeze(TOKEN_FORMAT);
